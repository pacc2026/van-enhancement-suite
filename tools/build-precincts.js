#!/usr/bin/env node
// Generates src/precinct-map.js from precincts.csv.
//
// The CSV is the source of truth: it comes straight out of BigQuery, is
// readable, and diffs cleanly when the turf plan changes. The generated JS is
// what ships, because the content scripts run in the MAIN world where
// chrome.runtime — and so chrome.runtime.getURL — does not exist. A .js file
// assigning a global is the only bundled-data format those scripts can read
// without a second isolated-world script bridging over postMessage.
//
// Usage: node tools/build-precincts.js [input.csv] [output.js]

'use strict';

var fs = require('fs');
var path = require('path');

var INPUT = process.argv[2] || 'precincts.csv';
var OUTPUT = process.argv[3] || path.join('src', 'precinct-map.js');

var REQUIRED_COLUMNS = ['van_county', 'van_precinct_name', 'folder', 'list_name'];

// Minimal RFC 4180 reader: handles quoted fields and embedded commas so a
// precinct named "Smith, North" cannot silently shift every later column.
function parseCsv(text) {
  var rows = [];
  var row = [];
  var field = '';
  var quoted = false;

  for (var i = 0; i < text.length; i += 1) {
    var c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i += 1; }
        else quoted = false;
      } else field += c;
      continue;
    }
    if (c === '"') { quoted = true; }
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') { field += c; }
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows.filter(function (r) { return r.some(function (f) { return f.trim(); }); });
}

// Matching key. Normalized on both sides so that a stray double space or a
// difference in case between VAN's dropdown label and the BigQuery export
// does not cause a miss.
function key(county, precinct) {
  var norm = function (s) { return s.replace(/\s+/g, ' ').trim().toLowerCase(); };
  return norm(county) + '|' + norm(precinct);
}

function main() {
  var rows = parseCsv(fs.readFileSync(INPUT, 'utf8'));
  if (!rows.length) throw new Error(INPUT + ' is empty');

  var header = rows[0].map(function (h) { return h.trim(); });
  REQUIRED_COLUMNS.forEach(function (name) {
    if (header.indexOf(name) === -1) {
      throw new Error('missing required column "' + name + '" in ' + INPUT + '; found: ' + header.join(', '));
    }
  });
  var at = {};
  REQUIRED_COLUMNS.forEach(function (name) { at[name] = header.indexOf(name); });

  // Folder names repeat across thousands of precincts, so intern them and
  // store an index per row.
  var folders = [];
  var folderIndex = Object.create(null);
  var map = Object.create(null);
  var duplicates = [];
  var skipped = 0;

  rows.slice(1).forEach(function (r) {
    var county = (r[at.van_county] || '').trim();
    var precinct = (r[at.van_precinct_name] || '').trim();
    var folder = (r[at.folder] || '').trim();
    var listName = (r[at.list_name] || '').trim();

    if (!county || !precinct || !listName) { skipped += 1; return; }

    if (!(folder in folderIndex)) {
      folderIndex[folder] = folders.length;
      folders.push(folder);
    }

    var k = key(county, precinct);
    if (k in map) duplicates.push(k);
    map[k] = [folderIndex[folder], listName];
  });

  var out = '// GENERATED by tools/build-precincts.js from ' + path.basename(INPUT) + ' — do not edit.\n'
    + '// Regenerate whenever the turf plan changes.\n'
    + 'window.__vesPrecincts = {\n'
    + '  folders: ' + JSON.stringify(folders) + ',\n'
    + '  rows: ' + JSON.stringify(map) + '\n'
    + '};\n';

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, out);

  console.log('wrote ' + OUTPUT);
  console.log('  precincts: ' + Object.keys(map).length);
  console.log('  folders:   ' + folders.length);
  console.log('  size:      ' + (out.length / 1024).toFixed(1) + ' KB');
  if (skipped) console.log('  skipped (incomplete rows): ' + skipped);
  if (duplicates.length) {
    console.log('  WARNING duplicate county+precinct keys (last wins): ' + duplicates.length);
    [...new Set(duplicates)].slice(0, 5).forEach(function (d) { console.log('    ' + d); });
  }
}

main();
